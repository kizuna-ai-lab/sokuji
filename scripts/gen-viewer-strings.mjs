#!/usr/bin/env node
// scripts/gen-viewer-strings.mjs
//
// Writes src/viewer/strings.generated.ts: the `viewer` subtree of every
// src/locales/<id>/translation.json, and nothing else. The LAN caption viewer
// imports this instead of the catalogs, because the main app imports the
// catalogs whole and the build then shares each one, every subtree included,
// with the viewer page (spec 2026-10-04 §5.7, §13). Re-run after changing any
// catalog's `viewer` strings; src/viewer/strings.test.ts fails until you do.
import { readdirSync, readFileSync, writeFileSync, statSync } from 'node:fs';
import { join } from 'node:path';

const root = process.cwd();
const locales = join(root, 'src', 'locales');
const words = {};
for (const id of readdirSync(locales).sort()) {
  const file = join(locales, id, 'translation.json');
  if (!statSync(join(locales, id)).isDirectory()) continue;
  const catalog = JSON.parse(readFileSync(file, 'utf8'));
  if (catalog.viewer) words[id] = catalog.viewer;
}

const out = `// Generated by scripts/gen-viewer-strings.mjs from src/locales/*/translation.json.
// Do not edit: change the catalogs, then run \`node scripts/gen-viewer-strings.mjs\`.
export const VIEWER_WORDS: Record<string, unknown> = ${JSON.stringify(words, null, 2)};
`;
writeFileSync(join(root, 'src', 'viewer', 'strings.generated.ts'), out);
process.stdout.write(`wrote src/viewer/strings.generated.ts (${Object.keys(words).length} catalogs)\n`);
