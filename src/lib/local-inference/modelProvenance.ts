/**
 * Model provenance — where every downloadable local model comes from, and the
 * terms its weights carry. One row per MODEL_MANIFEST entry, enforced by
 * modelProvenance.consistency.test.ts.
 *
 * The docs page that lists the local models (sokuji.kizuna.ai/docs/local-models)
 * is generated from these rows through localModelCatalog.ts. Traced to each
 * upstream and checked against its own license text in October 2026 (#584).
 */

// ─── Types ───────────────────────────────────────────────────────────────────

/**
 * How freely the weights may be used, read from the upstream license:
 * - open: permissive or attribution-only (MIT, Apache-2.0, BSD, CC0, CC BY, CC BY-SA)
 * - conditional: usable, with terms beyond attribution (territory, use policy,
 *   copyleft, terms inherited from the base model or training data)
 * - non-commercial: the upstream allows non-commercial use only, or commercial use
 *   only on its own terms
 * - unstated: the upstream grants no license at all
 * - cloud: not a download; text is sent to an online service
 */
export type LicenseTier = 'open' | 'conditional' | 'non-commercial' | 'unstated' | 'cloud';

/**
 * - non-commercial-base: fine-tuned from a voice whose training data is non-commercial
 *   (Piper lessac or ryan); the fine-tune's own license does not say whether those
 *   terms carry over
 * - removed-upstream: the publisher has withdrawn the model
 * - game-character: trained on a video game character's voice lines
 */
export type ProvenanceFlag = 'non-commercial-base' | 'removed-upstream' | 'game-character';

export interface ModelProvenance {
  /** The upstream checkpoint, as its publisher names it (e.g. 'nvidia/canary-180m-flash'). */
  upstream: string;
  upstreamUrl?: string;
  /** The upstream commit or release the shipped files were converted from, when known. */
  revision?: string;
  /**
   * The sherpa-onnx release archive a self-hosted package was rebuilt from. Absent for
   * a Hugging Face download, whose repo (the manifest's hfModelId) is the conversion.
   */
  via?: string;
  viaUrl?: string;
  /** SPDX id where one exists, otherwise the license's own name. */
  license: string;
  licenseUrl?: string;
  tier: LicenseTier;
  flags?: ProvenanceFlag[];
  /** One or two English sentences on what the terms restrict; required for every tier but open. */
  note?: string;
}

